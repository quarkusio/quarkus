package io.quarkus.runtime.util;

import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandleProxies;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;

/**
 * Initializes classes from a thread whose stack only contains JDK frames and whose context class loader is the
 * system class loader.
 * <p>
 * This is a dev and test mode facility for classes shared across application restarts (classes loaded by the
 * system class loader, or by a parent-first class loader) whose static initializer captures its surroundings: a
 * {@link Throwable} stored in a static field keeps, through its backtrace, the classes of every frame on the stack
 * when it was created, and a {@link Thread} created in a static initializer inherits the context class loader of the
 * thread initializing the class. When this happens from an application thread, the captured application class loader
 * can never be garbage collected.
 * <p>
 * The initialization runs in a dedicated thread, with a {@link Runnable} generated by {@link MethodHandleProxies} so
 * that no class loaded by an application class loader is on the stack, and with the system class loader as context
 * class loader.
 */
public final class IsolatedClassInitializer {

    private IsolatedClassInitializer() {
    }

    /**
     * Initializes the given classes in isolation, ignoring the classes that cannot be found or initialized.
     *
     * @param classLoader the class loader to load the classes from
     * @param classNames the names of the classes to initialize
     */
    public static void initialize(ClassLoader classLoader, String... classNames) {
        for (String className : classNames) {
            try {
                MethodHandle forName = MethodHandles.publicLookup()
                        .findStatic(Class.class, "forName",
                                MethodType.methodType(Class.class, String.class, boolean.class, ClassLoader.class))
                        .bindTo(className);
                forName = MethodHandles.insertArguments(forName, 0, true, classLoader);
                // the proxy class is generated by the JDK, so the stack of the thread only contains JDK frames
                Runnable task = MethodHandleProxies.asInterfaceInstance(Runnable.class,
                        forName.asType(MethodType.methodType(void.class)));
                Thread thread = new Thread(task, "isolated-class-initializer");
                thread.setDaemon(true);
                thread.setContextClassLoader(ClassLoader.getSystemClassLoader());
                thread.start();
                thread.join();
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                return;
            } catch (Throwable ignored) {
                // best effort
            }
        }
    }
}
