package io.quarkus.runtime.shutdown;

import java.lang.invoke.ConstantBootstraps;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.VarHandle;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;

import org.jboss.logging.Logger;

import io.quarkus.runtime.RuntimeValue;
import io.quarkus.runtime.annotations.Recorder;

/**
 * @deprecated Graceful shutdown is now handled by the service graph.
 *             Use {@link io.quarkus.core.StartContext#onGracefulPreShutdown(Runnable)} and
 *             {@link io.quarkus.core.StartContext#onGracefulShutdown(Runnable)} instead.
 */
@Deprecated(since = "4.0", forRemoval = true)
@Recorder
public class ShutdownRecorder {

    /**
     * Logger for ShutdownRecorder class.
     */
    private static final Logger log = Logger.getLogger(ShutdownRecorder.class);

    /**
     * VarHandle for atomic access to static {@code shutdownListeners}.
     */
    private static final VarHandle shutdownListenersHandle = ConstantBootstraps.staticFieldVarHandle(
            MethodHandles.lookup(), "shutdownListeners", VarHandle.class, ShutdownRecorder.class, List.class);

    /**
     * The list of legacy shutdown listeners.
     */
    @SuppressWarnings("unused") // Managed via VarHandle
    private static volatile List<ShutdownListener> shutdownListeners;

    /**
     * Legacy shutdown configuration.
     */
    private static volatile RuntimeValue<ShutdownConfig> shutdownConfig;

    /**
     * Legacy delay-enabled flag.
     */
    private static volatile boolean delayEnabled;

    /**
     * @deprecated Use {@link io.quarkus.core.StartContext#onGracefulPreShutdown(Runnable)} and
     *             {@link io.quarkus.core.StartContext#onGracefulShutdown(Runnable)} instead.
     */
    @Deprecated(since = "4.0", forRemoval = true)
    public ShutdownRecorder(RuntimeValue<ShutdownConfig> shutdownConfig) {
        ShutdownRecorder.shutdownConfig = shutdownConfig;
    }

    /**
     * Store legacy shutdown listeners. Called from generated bytecode during runtime init.
     * The listeners are read by the service graph during shutdown.
     *
     * @deprecated Use {@link io.quarkus.core.StartContext#onGracefulPreShutdown(Runnable)} and
     *             {@link io.quarkus.core.StartContext#onGracefulShutdown(Runnable)} instead.
     */
    @Deprecated(since = "4.0", forRemoval = true)
    public void setListeners(List<ShutdownListener> listeners, boolean delayEnabled) {
        shutdownListeners = Optional.ofNullable(listeners).orElseGet(List::of);
        ShutdownRecorder.delayEnabled = delayEnabled;
    }

    /**
     * @deprecated Runs the legacy graceful shutdown sequence for backward compatibility.
     */
    @Deprecated(since = "4.0", forRemoval = true)
    public static void runShutdown() {
        List<ShutdownListener> listeners = getLegacyListeners();
        if (listeners == null) {
            return;
        }
        log.debug("Attempting to gracefully shutdown.");
        try {
            executePreShutdown(listeners);
            waitForDelay();
            executeShutdown(listeners);
        } catch (Throwable e) {
            log.error("Graceful shutdown failed", e);
        }
    }

    /**
     * Executes the pre-shutdown phase for all registered legacy listeners.
     *
     * @param listeners the list of legacy shutdown listeners
     * @throws InterruptedException if the execution is interrupted while waiting
     */
    private static void executePreShutdown(List<ShutdownListener> listeners) throws InterruptedException {
        CountDownLatch preShutdown = new CountDownLatch(listeners.size());
        for (ShutdownListener i : listeners) {
            ShutdownAction.SHUTDOWN_LISTENER_PRESHUTDOWN.run(i.getClass().getName(), new Runnable() {
                @Override
                public void run() {
                    i.preShutdown(new LatchShutdownNotification(preShutdown));
                }
            });
        }
        preShutdown.await();
    }

    /**
     * Pauses execution for the configured graceful shutdown delay.
     */
    private static void waitForDelay() {
        if (delayEnabled && shutdownConfig.getValue().isDelayEnabled()) {
            try {
                Thread.sleep(shutdownConfig.getValue().delay().get().toMillis());
            } catch (InterruptedException e) {
                log.error("Interrupted while waiting for delay, continuing to shutdown immediately");
            }
        }
    }

    /**
     * Executes the shutdown phase for all registered legacy listeners, waiting up to the configured timeout.
     *
     * @param listeners the list of legacy shutdown listeners
     * @throws InterruptedException if the execution is interrupted while waiting
     */
    private static void executeShutdown(List<ShutdownListener> listeners) throws InterruptedException {
        CountDownLatch shutdown = new CountDownLatch(listeners.size());
        for (ShutdownListener i : listeners) {
            ShutdownAction.SHUTDOWN_LISTENER_SHUTDOWN.run(i.getClass().getName(), new Runnable() {
                @Override
                public void run() {
                    i.shutdown(new LatchShutdownNotification(shutdown));
                }
            });
        }
        if (shutdownConfig.getValue().isTimeoutEnabled()
                && !shutdown.await(shutdownConfig.getValue().timeout().get().toMillis(), TimeUnit.MILLISECONDS)) {
            log.error("Timed out waiting for graceful shutdown, shutting down anyway.");
        }
    }

    /**
     * A {@link ShutdownListener.ShutdownNotification} implementation backed by a {@link CountDownLatch}.
     */
    private static class LatchShutdownNotification implements ShutdownListener.ShutdownNotification {
        /**
         * The backing count down latch.
         */
        private final CountDownLatch latch;

        /**
         * Constructs a new LatchShutdownNotification with the specified latch.
         *
         * @param latch the latch to count down when done is called
         */
        public LatchShutdownNotification(CountDownLatch latch) {
            this.latch = latch;
        }

        /**
         * Signals that the shutdown listener has completed its shutdown phase.
         */
        @Override
        public void done() {
            latch.countDown();
        }
    }

    /**
     * Get the legacy shutdown listeners, or {@code null} if none were registered.
     * Used by the service graph to bridge legacy listeners into the new mechanism.
     *
     * @return the list of legacy listeners, or {@code null}
     */
    @SuppressWarnings("unchecked")
    public static List<ShutdownListener> getLegacyListeners() {
        return (List<ShutdownListener>) shutdownListenersHandle.getAndSet(null);
    }

    /**
     * Get the legacy shutdown config.
     *
     * @return the shutdown config runtime value, or {@code null}
     */
    public static ShutdownConfig getLegacyShutdownConfig() {
        RuntimeValue<ShutdownConfig> rv = shutdownConfig;
        return rv != null ? rv.getValue() : null;
    }

    /**
     * Get the legacy delay-enabled flag.
     *
     * @return whether the delay was enabled at build time
     */
    public static boolean isLegacyDelayEnabled() {
        return delayEnabled;
    }
}
